// Package product holds the catalog domain: commercial variants (SKU) of PVC rolls
// and finished tablecloths. A SKU identifies a variant, not a physical roll.
package product

import (
	"regexp"
	"strings"
	"time"
	"unicode/utf8"

	"gumunova/backend/internal/domain/shared/decimal"
	"gumunova/backend/internal/domain/shared/validation"
)

type Type string

const (
	TypePVC        Type = "pvc"
	TypeTablecloth Type = "tablecloth"
)

const (
	maxSKULength       = 40
	minSKULength       = 3
	maxNameLength      = 120
	maxAttributeLength = 80
	maxDimensionLength = 80
	maxMinimumUnits    = 100_000
)

var skuPattern = regexp.MustCompile(`^[A-Z0-9][A-Z0-9_-]*$`)

// PVCDetails are the attributes of a PVC roll variant.
type PVCDetails struct {
	Material               string
	Design                 string
	Color                  string
	Texture                string
	WidthM                 decimal.Decimal
	NominalLengthM         decimal.Decimal
	ThicknessMM            *decimal.Decimal
	ReferencePricePerMeter decimal.Decimal
	ReferencePricePerRoll  decimal.Decimal
	// MinimumStockM flags low stock when the available meters of all rolls fall to it or below.
	// Zero disables the alert.
	MinimumStockM decimal.Decimal
}

// TableclothDetails are the attributes of a finished tablecloth variant.
type TableclothDetails struct {
	Design        string
	Color         string
	Dimensions    string
	ReferenceCost *decimal.Decimal
	UnitPrice     decimal.Decimal
	// MinimumUnits flags low stock when the units available fall to it or below. Zero disables the alert.
	MinimumUnits int
}

// Product is a catalog entry. Exactly one of PVC or Tablecloth is set, matching Type.
type Product struct {
	ID       string
	SKU      string
	Name     string
	Type     Type
	IsActive bool
	ImageKey string
	// LabelCode is the unique code printed on labels (QR or barcode). It is assigned and
	// regenerated by persistence, never edited with the rest of the product data.
	LabelCode  string
	PVC        *PVCDetails
	Tablecloth *TableclothDetails
	CreatedAt  time.Time
	UpdatedAt  time.Time
}

// Draft is the editable data of a product, as received from a use case.
type Draft struct {
	SKU        string
	Name       string
	Type       Type
	PVC        *PVCDetails
	Tablecloth *TableclothDetails
}

// New builds a valid, active product from a draft. The SKU is normalized to upper case.
func New(draft Draft) (Product, error) {
	draft.SKU = strings.ToUpper(strings.TrimSpace(draft.SKU))
	draft.Name = strings.TrimSpace(draft.Name)
	trimDetails(&draft)

	if err := validate(draft); err != nil {
		return Product{}, err
	}
	return Product{
		SKU:        draft.SKU,
		Name:       draft.Name,
		Type:       draft.Type,
		IsActive:   true,
		PVC:        draft.PVC,
		Tablecloth: draft.Tablecloth,
	}, nil
}

// Revise replaces the editable data. SKU and type never change after creation,
// so the draft's SKU and type are ignored.
func (p *Product) Revise(draft Draft) error {
	draft.SKU = p.SKU
	draft.Type = p.Type
	draft.Name = strings.TrimSpace(draft.Name)
	trimDetails(&draft)

	if err := validate(draft); err != nil {
		return err
	}
	p.Name = draft.Name
	p.PVC = draft.PVC
	p.Tablecloth = draft.Tablecloth
	return nil
}

func (p *Product) Activate()   { p.IsActive = true }
func (p *Product) Deactivate() { p.IsActive = false }

func trimDetails(draft *Draft) {
	if draft.PVC != nil {
		details := *draft.PVC
		details.Material = strings.TrimSpace(details.Material)
		details.Design = strings.TrimSpace(details.Design)
		details.Color = strings.TrimSpace(details.Color)
		details.Texture = strings.TrimSpace(details.Texture)
		draft.PVC = &details
	}
	if draft.Tablecloth != nil {
		details := *draft.Tablecloth
		details.Design = strings.TrimSpace(details.Design)
		details.Color = strings.TrimSpace(details.Color)
		details.Dimensions = strings.TrimSpace(details.Dimensions)
		draft.Tablecloth = &details
	}
}

func validate(draft Draft) error {
	var problems []FieldError
	add := func(field, code string) { problems = append(problems, FieldError{Field: field, Code: code}) }

	validateSKU(draft.SKU, add)

	switch {
	case draft.Name == "":
		add("name", CodeRequired)
	case utf8.RuneCountInString(draft.Name) > maxNameLength:
		add("name", CodeTooLong)
	}

	switch draft.Type {
	case TypePVC:
		if draft.Tablecloth != nil {
			add("tablecloth", CodeNotAllowed)
		}
		if draft.PVC == nil {
			add("pvc", CodeRequired)
		} else {
			validatePVC(*draft.PVC, add)
		}
	case TypeTablecloth:
		if draft.PVC != nil {
			add("pvc", CodeNotAllowed)
		}
		if draft.Tablecloth == nil {
			add("tablecloth", CodeRequired)
		} else {
			validateTablecloth(*draft.Tablecloth, add)
		}
	default:
		add("product_type", CodeInvalidValue)
	}

	if len(problems) > 0 {
		return &ValidationError{Fields: problems}
	}
	return nil
}

func validateSKU(sku string, add func(field, code string)) {
	switch {
	case sku == "":
		add("sku", CodeRequired)
	case utf8.RuneCountInString(sku) < minSKULength || utf8.RuneCountInString(sku) > maxSKULength:
		add("sku", CodeInvalidLength)
	case !skuPattern.MatchString(sku):
		add("sku", CodeInvalidFormat)
	}
}

func validatePVC(details PVCDetails, add func(field, code string)) {
	checkText("pvc.material", details.Material, maxAttributeLength, add)
	checkText("pvc.design", details.Design, maxAttributeLength, add)
	checkText("pvc.color", details.Color, maxAttributeLength, add)
	checkText("pvc.texture", details.Texture, maxAttributeLength, add)

	if !details.WidthM.IsPositive() {
		add("pvc.width_m", CodeMustBePositive)
	}
	if !details.NominalLengthM.IsPositive() {
		add("pvc.nominal_length_m", CodeMustBePositive)
	}
	if details.MinimumStockM.IsNegative() {
		add("pvc.minimum_stock_m", CodeMustNotBeNegative)
	}
	if details.ThicknessMM != nil && !details.ThicknessMM.IsPositive() {
		add("pvc.thickness_mm", CodeMustBePositive)
	}
	if !details.ReferencePricePerMeter.IsPositive() {
		add("pvc.reference_price_per_meter", CodeMustBePositive)
	}
	if !details.ReferencePricePerRoll.IsPositive() {
		add("pvc.reference_price_per_roll", CodeMustBePositive)
	}
}

func validateTablecloth(details TableclothDetails, add func(field, code string)) {
	checkText("tablecloth.design", details.Design, maxAttributeLength, add)
	checkText("tablecloth.color", details.Color, maxAttributeLength, add)
	checkText("tablecloth.dimensions", details.Dimensions, maxDimensionLength, add)

	if details.ReferenceCost != nil && details.ReferenceCost.IsNegative() {
		add("tablecloth.reference_cost", CodeMustNotBeNegative)
	}
	if !details.UnitPrice.IsPositive() {
		add("tablecloth.unit_price", CodeMustBePositive)
	}
	switch {
	case details.MinimumUnits < 0:
		add("tablecloth.minimum_units", CodeMustNotBeNegative)
	case details.MinimumUnits > maxMinimumUnits:
		add("tablecloth.minimum_units", validation.CodeOutOfRange)
	}
}

func checkText(field, value string, maxLength int, add func(field, code string)) {
	if utf8.RuneCountInString(value) > maxLength {
		add(field, CodeTooLong)
	}
}
